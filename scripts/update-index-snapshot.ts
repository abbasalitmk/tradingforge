/**
 * Refresh the NSE index-constituent snapshot the dashboard falls back to when
 * NSE cannot be reached. Run after NSE's semi-annual rebalances:
 *
 *   node --experimental-strip-types scripts/update-index-snapshot.ts
 */
import { writeFileSync } from 'node:fs';
import { INDEX_CATEGORIES, NSE_INDEX_ARCHIVE, parseConstituents } from '../apps/web/src/lib/market/indices.ts';

const OUT = new URL('../apps/web/src/lib/market/indices-snapshot.ts', import.meta.url);

const stocks = new Map<string, [string, string, string]>();
const members: Record<string, string[]> = {};
for (const c of INDEX_CATEGORIES) {
  const res = await fetch(NSE_INDEX_ARCHIVE + c.file, { headers: { 'user-agent': 'Mozilla/5.0 (TradeForger snapshot)' } });
  if (!res.ok) throw new Error(`${c.id}: HTTP ${res.status}`);
  const list = parseConstituents(await res.text());
  if (list.length === 0) throw new Error(`${c.id}: empty`);
  members[c.id] = list.map((s) => s.symbol);
  for (const s of list) stocks.set(s.symbol, [s.name, s.industry, s.isin]);
  console.log(`${c.id.padEnd(24)} ${list.length}`);
}

const date = new Date().toISOString().slice(0, 10);
const q = (s: string) => JSON.stringify(s);
const body = [
  '// Generated by scripts/update-index-snapshot.ts; do not edit by hand.',
  `export const SNAPSHOT_DATE = ${q(date)};`,
  '',
  '/** symbol → [company name, industry, ISIN] */',
  'export const STOCKS: Readonly<Record<string, readonly [string, string, string]>> = {',
  ...[...stocks].sort(([a], [b]) => a.localeCompare(b)).map(([sym, v]) => `  ${q(sym)}: [${v.map(q).join(', ')}],`),
  '};',
  '',
  'export const MEMBERS: Readonly<Record<string, readonly string[]>> = {',
  ...Object.entries(members).map(([id, syms]) => `  ${id}: [${syms.map(q).join(', ')}],`),
  '};',
  '',
].join('\n');
writeFileSync(OUT, body);
console.log(`${stocks.size} unique stocks → ${OUT.pathname}`);
